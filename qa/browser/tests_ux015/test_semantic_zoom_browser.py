from playwright.sync_api import sync_playwright
from pathlib import Path
import json
BASE=Path(__file__).resolve().parents[1]; checks=[]
def ck(value,label):
 checks.append({'name':label,'passed':bool(value)})
 if not value: raise AssertionError(label)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1280,'height':860},device_scale_factor=1)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.evaluate('''window.__memoryLocal={};Object.defineProperty(window,'localStorage',{value:{getItem:k=>window.__memoryLocal[k]??null,setItem:(k,v)=>{window.__memoryLocal[k]=String(v)},removeItem:k=>{delete window.__memoryLocal[k]},clear:()=>{window.__memoryLocal={}}}})''')
 page.set_content((BASE/'site_source/public/index.html').read_text(),wait_until='load')
 before=page.evaluate('''()=>__graphite.getState()''')
 ck(len(before['nodes'])>=18,'fixture contains large story')
 page.evaluate('()=>__graphite.setZoomForTest(.9)')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='full','full card mode at near zoom')
 ck(page.locator('.pa-semantic-item').count()==0,'no extra captions in full card mode')
 page.evaluate('()=>__graphite.setZoomForTest(.48)')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='compact','compact mode at medium zoom')
 ck(page.locator('.pa-semantic-item').count()>0,'compact labels appear')
 ck(page.evaluate('()=>getComputedStyle(document.querySelector(".node")).visibility')=='hidden','original card hidden in compact mode')
 ck(page.locator('.overview-title').count()==0,'legacy overlay captions removed')
 ck(page.locator('.pa-semantic-dot').count()==page.locator('.pa-semantic-item').count(),'each visible compact node has anchored marker')
 ck(page.locator('.pa-semantic-label:not([hidden])').count()>0,'some compact text is visible')
 page.evaluate('()=>__graphite.setZoomForTest(.65)')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='compact','hysteresis prevents flicker at 65%')
 page.evaluate('()=>__graphite.setZoomForTest(.70)')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='full','close zoom restores full cards')
 page.evaluate('()=>__graphite.setZoomForTest(.24)')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='map','far view uses map level')
 ck(page.locator('.node:visible').count()==0,'no empty background card rectangles on far zoom')
 ck(page.locator('.pa-semantic-dot').count()==len(before['nodes']),'all visible fixture events have map markers')
 ck(page.locator('.pa-semantic-label:not([hidden])').count()>0,'far labels are readable')
 dots=page.evaluate('''()=>[...document.querySelectorAll('.pa-semantic-item')].map(n=>({id:n.dataset.zoomNode,x:parseFloat(n.style.left),y:parseFloat(n.style.top)}))''')
 pan=page.evaluate('()=>__graphite.getPan()')
 ck(all(abs(d['x']-(pan['x']+(next(n for n in before['nodes'] if n['id']==d['id'])['x']+page.evaluate('''id=>document.querySelector(`.node[data-node="${id}"]`).offsetWidth''',d['id'])/2)*pan['scale']))<1.3 for d in dots[:5]),'fixed anchors track physical node centers')
 labels=page.evaluate('''()=>[...document.querySelectorAll('.pa-semantic-label:not([hidden])')].map(n=>{const r=n.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}})''')
 def overlap(a,b):return a['x']<b['x']+b['w'] and b['x']<a['x']+a['w'] and a['y']<b['y']+b['h'] and b['y']<a['y']+a['h']
 ck(all(not overlap(a,b) for i,a in enumerate(labels) for b in labels[i+1:]),'screen labels do not overlap')
 after=page.evaluate('()=>__graphite.getState()')
 ck(after['revision']==before['revision'],'zoom and map rendering cause no persisted revisions')
 ck(after['edges']==before['edges'] and after['fields']==before['fields'],'edges and fields unchanged')
 ck([{k:v for k,v in n.items() if k!='autoFieldIds'} for n in after['nodes']]==[{k:v for k,v in n.items() if k!='autoFieldIds'} for n in before['nodes']],'node geometry and content remain unchanged')
 page.locator('.pa-semantic-item').first.click()
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='full','far marker click zooms to full event')
 ck(page.evaluate('()=>__graphite.getSelected().type')=='node','far click selects original event')
 page.evaluate('()=>__graphite.setZoomForTest(.48)')
 page.locator('.pa-semantic-item').first.click(button='right')
 ck(page.locator('#pa-context-menu').is_visible(),'context menu opens on overview item')
 ck(page.locator('#pa-context-menu').get_attribute('data-context-kind')=='node','context menu targets node, not canvas')
 page.keyboard.press('Escape')
 ck(not page.locator('#pa-context-menu').is_visible(),'escape dismisses context menu')
 page.evaluate('()=>__graphite.selectNodes([])')
 page.evaluate('()=>__graphite.setZoomForTest(.48)')
 node=page.locator('.pa-semantic-item').first
 nid=node.get_attribute('data-zoom-node');node.click()
 ck(page.evaluate('()=>__graphite.getSelected().id')==nid,'medium click selects correct node')
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='compact','first medium click stays at compact scale')
 page.locator(f'.pa-semantic-item[data-zoom-node="{nid}"]').click()
 ck(page.evaluate('()=>__graphite.getSemanticZoom()')=='full','second medium click returns to event details')
 ck(page.evaluate('()=>__graphite.getState().revision')==before['revision'],'overview interactions remain read-only')
 page.evaluate('()=>__graphite.setZoomForTest(.24)')
 page.screenshot(path=str(BASE/'UX015_MAP.png'))
 page.evaluate('()=>__graphite.setZoomForTest(.48)')
 page.screenshot(path=str(BASE/'UX015_COMPACT.png'))
 ck(not errors,'no browser JavaScript errors')
 browser.close()
(BASE/'UX015_BROWSER_QA.json').write_text(json.dumps({'passed':len(checks),'checks':checks},indent=2,ensure_ascii=False))
print(json.dumps({'passed':len(checks),'errors':errors},ensure_ascii=False))
