from playwright.sync_api import sync_playwright
from pathlib import Path
import json,sys
BASE=Path(__file__).resolve().parents[1]
checks=[]
def ck(cond, message):
    checks.append({'name':message,'passed':bool(cond)})
    if not cond: raise AssertionError(message)

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1365,'height':920},device_scale_factor=1)
    page=context.new_page()
    errs=[]
    page.on('pageerror',lambda e: errs.append(str(e)))
    mockstorage = """window.__memoryLocal={};Object.defineProperty(window,'localStorage',{value:{getItem:k=>window.__memoryLocal[k]??null,setItem:(k,v)=>{window.__memoryLocal[k]=String(v)},removeItem:k=>{delete window.__memoryLocal[k]},clear:()=>{window.__memoryLocal={}}}})"""
    page.evaluate(mockstorage)
    html=(BASE/'site_source/public/index.html').read_text()
    page.set_default_timeout(7000)
    page.set_content(html,wait_until='load')
    page.evaluate('''()=>{localStorage.clear();__graphite.reset()}''')
    fixture={'version':1,'revision':3,'view':None,'nextNode':5,'nextEdge':4,'nextField':3,'nextLine':3,
      'nodes':[{'id':'n1','title':'Ужас','description':'Сначала договор кажется выгодным.\nНо совет замечает опасные условия.\n'+('Очень длинное исходное описание. '*20),'x':260,'y':280,'lineIds':['l1'],'status':'approved','parent':None},
               {'id':'n2','title':'Следствие','description':'Продолжение','x':685,'y':290,'lineIds':['l1'],'parent':None}],
      'edges':[{'id':'e1','from':'n1','to':'n2','type':'causes'}],
      'fields':[{'id':'f1','title':'Совет','color':'#b8a16e','x':180,'y':200,'width':850,'height':400,'assignmentMode':'auto','parent':None},{'id':'f2','title':'Другое поле','color':'#8a9d83','x':1200,'y':700,'width':300,'height':250,'assignmentMode':'auto','parent':None}],
      'lanes':[{'id':'l1','title':'Основная линия','color':'#b8a16e','y':180},{'id':'l2','title':'Другие','color':'#8a9d83','y':500}]}
    page.evaluate('(f)=>__graphite.loadFixture(f)',fixture)
    page.evaluate("()=>__graphite.selectNode('n1')")
    inspector=page.locator('#inspector')
    ck(inspector.is_visible(),'inspector appears when selecting event')
    v=page.evaluate('''()=>{const s=getComputedStyle(document.querySelector('#inspector'));return {width:s.width,maxHeight:s.maxHeight,overflowY:s.overflowY}}''')
    ck(v['width']=='370px','existing 370px width unchanged')
    ck(v['overflowY']=='auto' and v['maxHeight'] in ('662.4px','662px','680px'),'existing max-height and scroll unchanged')
    labels=inspector.locator('.field > label:not(.check-row)').all_text_contents()
    ck([x.strip() for x in labels[:5]]==['Название','Описание','Сюжетные линии','Смысловые поля','Цвет карточки'],'inspector groups in approved order')
    ck(inspector.locator('#i-open').count()==0 and page.locator('[data-node="n1"] [data-command="inside"]').count()==1,'inside action only on canvas node')
    ck(inspector.locator('[data-actual-tag]').count()==1,'inspector shows only active semantic field')
    ck(inspector.locator('[data-line-check]').count()==2,'line checkboxes remain')
    ck(not page.locator('[data-line-check="l2"]').is_checked(),'second line initially unchecked')
    page.locator('[data-line-check="l1"]').click();ck(page.locator('[data-line-check="l1"]').is_checked(),'cannot unset last storyline')
    original=page.evaluate('()=>__graphite.getState()')
    page.locator('#i-rewrite').click()
    started=page.evaluate('()=>__graphite.getState()')
    ck(len(started['eventRewrites'])==1 and started['eventRewrites'][0]['nodeId']=='n1','rewrite draft attached to node ID')
    ck([{k:v for k,v in n.items() if k!='autoFieldIds'} for n in started['nodes']]==[{k:v for k,v in n.items() if k!='autoFieldIds'} for n in original['nodes']] and started['edges']==original['edges'],'entering rewrite preserves canonical nodes and edges')
    ck(started['gapNotes']==original['gapNotes'] and started['gapLinks']==original['gapLinks'],'no independent gap note or causal/editorial edge added')
    ck(page.locator('#rewrite-heading').is_visible(),'rewrite heading shown')
    ck(page.locator('.ux014-original-title').inner_text()=='Ужас','source title always visible')
    ck(page.locator('.ux014-original-description').inner_text()==fixture['nodes'][0]['description'],'source description fully visible by default')
    ck(page.locator('details').count()==0,'no collapsing original-description control')
    ck(page.locator('.node.rewrite-draft').count()==1 and page.locator('[data-node="n1"] .ux014-node-kind').inner_text()=='▤ Заметка · переработка','canvas node becomes distinct editorial appearance')
    ck(page.locator('#ux014-offer').count()==0 and '3 варианта' not in page.locator('[data-node="n1"]').inner_text(),'CW-006 has no fixed variant choice')
    ck(page.locator('.ux014-generate').is_disabled(),'no fake generation prior to P5/P6')
    page.locator('#rewrite-heading').hover()
    page.wait_for_timeout(450)
    tip=page.locator('#hover-help')
    ck(tip.is_visible(),'tooltip appears on heading hover')
    ck('Исходное событие' in tip.inner_text() and 'То же место на графе' in tip.inner_text(),'both service messages only in tooltip')
    ck(page.locator('.ux014-original').inner_text().find('Исходное событие')==-1,'service labels absent from inspector body')
    ck(page.evaluate("getComputedStyle(document.querySelector('#hover-help')).whiteSpace")=='pre-line','tooltip has two distinct readable lines')
    t=tip.bounding_box();ck(bool(t and t['x']>=0 and t['y']>=0 and t['x']+t['width']<=1365),'tooltip within viewport')
    page.locator('#rewrite-heading').focus();page.wait_for_timeout(380)
    ck(tip.is_visible(),'tooltip keyboard focus enabled')
    page.keyboard.press('Escape');ck(not tip.is_visible(),'tooltip hides on escape')
    page.evaluate('()=>__graphite.selectNode("n1")')
    task='Сделать конфликт сильнее; при этом сохранить все подтверждённые факты.\nДобавить несколько возможных последствий.'
    page.locator('#ux014-task').fill(task)
    edited=page.evaluate('()=>__graphite.getState()')
    ck(edited['eventRewrites'][0]['taskText']==task,'task saved in draft')
    ck([{k:v for k,v in n.items() if k!='autoFieldIds'} for n in edited['nodes']]==[{k:v for k,v in n.items() if k!='autoFieldIds'} for n in original['nodes']] and edited['edges']==original['edges'],'typing does not overwrite source content')
    ck(task in page.locator('[data-node="n1"] .node-note').inner_text(),'task displayed on canvas')
    ck(page.evaluate('()=>__graphite.getEventRewrites()[0].offerVariants') is True,'legacy boolean remains only for serialization')
    page.evaluate('()=>__graphite.selectNode("n2")')
    page.evaluate('()=>__graphite.selectNode("n1")')
    ck(page.locator('#ux014-task').input_value()==task and page.locator('#ux014-offer').count()==0,'switching node selection retains draft without fixed-count toggle')
    persisted=page.evaluate('()=>structuredClone(window.__memoryLocal)')
    page.close()
    page=context.new_page()
    page.on('pageerror',lambda e: errs.append(str(e)))
    page.evaluate('window.__memoryLocal='+json.dumps(persisted,ensure_ascii=False)+';Object.defineProperty(window,\'localStorage\',{value:{getItem:k=>window.__memoryLocal[k]??null,setItem:(k,v)=>{window.__memoryLocal[k]=String(v)},removeItem:k=>{delete window.__memoryLocal[k]},clear:()=>{window.__memoryLocal={}}}})')
    page.set_content(html,wait_until='load')
    page.evaluate('()=>__graphite.selectNode("n1")')
    ck(page.locator('#ux014-task').input_value()==task and page.locator('#ux014-offer').count()==0,'localStorage reload restores draft without retired option')
    ck(page.evaluate('()=>__graphite.getState().nodes[0].title')=='Ужас','reload preserves original title')
    page.screenshot(path=str(BASE/'UX014_INTEGRATED_REWRITE.png'),full_page=True)
    page.locator('#ux014-cancel').click()
    ck(len(page.evaluate('()=>__graphite.getEventRewrites()'))==0,'cancel removes only draft')
    ck(page.locator('#field-title').input_value()=='Ужас' and page.evaluate('()=>__graphite.getState().edges[0].type')=='causes','cancel restores original event and arrows')
    page.evaluate('()=>__graphite.undo()')
    ck(len(page.evaluate('()=>__graphite.getEventRewrites()'))==1,'undo recovers canceled draft')
    # Use safe delete action and verify dependent cleanup and undo.
    page.evaluate('()=>__graphite.selectNode("n1")')
    page.evaluate('()=>__graphite.deletePlotNode("n1")')
    ck(page.locator('#ux014-delete-dialog').is_visible(),'delete confirmation appears')
    text=page.locator('#ux014-delete-dialog').inner_text()
    ck('Сюжетные связи: 1' in text and 'черновик переработки' in text,'delete confirmation counts affected edges and draft')
    page.locator('#ux014-delete-cancel').click()
    ck(len(page.evaluate('()=>__graphite.getState().nodes'))==2,'delete cancellation safe')
    page.evaluate('()=>__graphite.deletePlotNode("n1")')
    page.locator('#ux014-delete-confirm').click()
    after=page.evaluate('()=>__graphite.getState()')
    ck(len(after['nodes'])==1 and len(after['edges'])==0 and len(after['eventRewrites'])==0,'confirmed delete removes node, associated edges and draft')
    page.evaluate('()=>__graphite.undo()')
    after=page.evaluate('()=>__graphite.getState()')
    ck(len(after['nodes'])==2 and len(after['edges'])==1 and len(after['eventRewrites'])==1,'single undo recovers full delete state')
    # Child detail safeguard.
    page.evaluate('''()=>{__graphite.loadFixture({version:1,revision:0,view:null,nextNode:3,nextEdge:1,nextLine:2,nextField:1,nodes:[{id:'n1',title:'Родитель',description:'',x:100,y:100,lineIds:['l1'],parent:null},{id:'n2',title:'Дочернее',description:'',x:100,y:100,lineIds:['l1'],parent:'n1'}],edges:[],fields:[],lanes:[{id:'l1',title:'Линия',color:'#b8a16e',y:200}]});__graphite.selectNode('n1');__graphite.deletePlotNode('n1')}''')
    ck(page.locator('#ux014-delete-dialog').count()==0 and len(page.evaluate('()=>__graphite.getState().nodes'))==2,'cannot silently delete parent with children')
    ck(not errs,'no JS runtime errors: '+str(errs))
    # Main inspector screenshot with synthetic fixture
    page.evaluate('(f)=>__graphite.loadFixture(f)',fixture)
    page.evaluate('()=>__graphite.selectNode("n1")')
    page.screenshot(path=str(BASE/'UX014_INTEGRATED_EVENT.png'),full_page=True)
    context.close();browser.close()
report={'passed':sum(x['passed'] for x in checks),'total':len(checks),'checks':checks,'errors':errs}
(BASE/'UX014_BROWSER_QA.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf8')
print(json.dumps({'passed':report['passed'],'total':report['total'],'errors':errs},ensure_ascii=False))
